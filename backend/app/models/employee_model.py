"""
Employee model - HR profile and organizational data.

Separate from user_model.py to maintain clean separation:
- user_model.py = Authentication, login, roles
- employee_model.py = HR profile, department, designation, reporting, leaves, claims

Pattern:
- One user can have one employee profile via user_id
- Employee references master data collections
- Leave balances are initialized from leave_types
- Claim limits are initialized from claim_types
- Soft delete is handled using is_active and employment_status

Important:
- Employee code is unique and usually auto-generated by service layer
- Manager validation and circular reference checks should be handled in service layer
- Department/designation existence validation should be handled in service layer
- Leave/claim balances are dynamic and tracked per year
- Sensitive data should be returned only to authorized users
"""

