class LeaveBalance(BaseModel):
    """Leave balance for a specific leave type and year."""

    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_assignment=True,
    )

    leave_type_id: str = Field(..., description="Reference to leave_types._id")
    leave_type_code: str = Field(..., min_length=2, max_length=30)
    leave_type_name: str = Field(..., min_length=2, max_length=100)

    granted: float = Field(default=0.0, ge=0.0, description="Granted leave days")
    used: float = Field(default=0.0, ge=0.0, description="Used leave days")
    available: float = Field(default=0.0, ge=0.0, description="Available leave days")
    carried_forward: float = Field(default=0.0, ge=0.0)
    encashed: float = Field(default=0.0, ge=0.0)

    year: int = Field(..., ge=2000, le=2100, description="Leave year")

    @field_validator("leave_type_code")
    @classmethod
    def normalize_leave_type_code(cls, value: str) -> str:
        value = value.strip().upper()
        if not value.replace("_", "").replace("-", "").isalnum():
            raise ValueError("leave_type_code can contain only letters, numbers, hyphen, and underscore")
        return value

    @model_validator(mode="after")
    def validate_leave_balance(self):
        """
        Validate leave balance consistency.

        Formula:
        available should not exceed granted + carried_forward.
        used + encashed should not exceed granted + carried_forward unless
        negative balance is explicitly allowed later by leave service.
        """
        total_entitled = self.granted + self.carried_forward

        if self.available > total_entitled:
            raise ValueError("available leave cannot exceed granted + carried_forward")

        if self.used + self.encashed > total_entitled:
            raise ValueError("used + encashed cannot exceed granted + carried_forward")

        return self


class ClaimLimit(BaseModel):
    """Claim limit for a specific claim type and year."""

    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_assignment=True,
    )

    claim_type_id: str = Field(..., description="Reference to claim_types._id")
    claim_type_code: str = Field(..., min_length=2, max_length=30)
    claim_type_name: str = Field(..., min_length=2, max_length=100)

    annual_limit: float = Field(default=0.0, ge=0.0)
    monthly_limit: Optional[float] = Field(default=None, ge=0.0)

    used: float = Field(default=0.0, ge=0.0)
    available: float = Field(default=0.0, ge=0.0)

    year: int = Field(..., ge=2000, le=2100)

    @field_validator("claim_type_code")
    @classmethod
    def normalize_claim_type_code(cls, value: str) -> str:
        value = value.strip().upper()
        if not value.replace("_", "").replace("-", "").isalnum():
            raise ValueError("claim_type_code can contain only letters, numbers, hyphen, and underscore")
        return value

    @model_validator(mode="after")
    def validate_claim_limit(self):
        if self.monthly_limit is not None and self.monthly_limit > self.annual_limit:
            raise ValueError("monthly_limit cannot be greater than annual_limit")

        if self.used > self.annual_limit:
            raise ValueError("used claim amount cannot exceed annual_limit")

        if self.available > self.annual_limit:
            raise ValueError("available claim amount cannot exceed annual_limit")

        return self


