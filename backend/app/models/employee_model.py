PHONE_PATTERN = re.compile(r"^\+?[0-9][0-9\s\-]{8,18}[0-9]$")
PAN_PATTERN = re.compile(r"^[A-Z]{5}[0-9]{4}[A-Z]$")
IFSC_PATTERN = re.compile(r"^[A-Z]{4}0[A-Z0-9]{6}$")
AADHAAR_PATTERN = re.compile(r"^[0-9]{12}$")
PINCODE_PATTERN = re.compile(r"^[0-9A-Za-z][0-9A-Za-z\s\-]{2,18}[0-9A-Za-z]$")


def normalize_optional_text(value: Optional[str]) -> Optional[str]:
    """
    Strip optional text fields.

    Empty strings become None.
    """
    if value is None:
        return None

    value = str(value).strip()
    return value or None


def normalize_phone(value: Optional[str]) -> Optional[str]:
    """
    Normalize and validate phone number.

    Allows:
    - digits
    - +
    - spaces
    - hyphen
    """
    value = normalize_optional_text(value)

    if value is None:
        return None

    if not PHONE_PATTERN.match(value):
        raise ValueError("Invalid phone number format")

    return value


def normalize_pincode(value: Optional[str]) -> Optional[str]:
    """
    Normalize and validate postal/pincode value.
    """
    value = normalize_optional_text(value)

    if value is None:
        return None

    if not PINCODE_PATTERN.match(value):
        raise ValueError("Invalid pincode/postal code format")

    return value


def mask_value(value: Optional[str], visible_last: int = 4) -> Optional[str]:
    """
    Mask sensitive values for safe responses.

    Example:
    123456789012 -> ********9012
    """
    if not value:
        return None

    value = str(value)

    if len(value) <= visible_last:
        return "*" * len(value)

    return "*" * (len(value) - visible_last) + value[-visible_last:]


