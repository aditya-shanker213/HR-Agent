class Employee(BaseModel):
    """
    Employee document model for employees collection.

    Represents HR profile and organizational data.
    """

    model_config = ConfigDict(
        str_strip_whitespace=True,
        validate_assignment=True,
    )

    # -------------------------
    # Multi-company Support
    # -------------------------

    company_id: str = Field(
        default="default",
        min_length=2,
        max_length=100,
        description="Company identifier for future multi-tenant support",
    )

    # -------------------------
    # Core Identity
    # -------------------------

    employee_code: str = Field(
        ...,
        min_length=3,
        max_length=30,
        description="Unique employee code, usually auto-generated by service layer",
    )

    user_id: str = Field(
        ...,
        description="Reference to users._id for authentication",
    )

    # -------------------------
    # Personal Information
    # -------------------------

    first_name: str = Field(..., min_length=2, max_length=100)
    middle_name: Optional[str] = Field(default=None, max_length=100)
    last_name: str = Field(..., min_length=2, max_length=100)

    email: EmailStr = Field(..., description="Official company email")
    personal_email: Optional[EmailStr] = Field(default=None)

    phone: str = Field(..., min_length=10, max_length=20)
    alternate_phone: Optional[str] = Field(default=None, max_length=20)

    date_of_birth: Optional[date] = Field(default=None)

    gender: Optional[Gender] = Field(default=None)
    marital_status: Optional[MaritalStatus] = Field(default=None)
    blood_group: Optional[BloodGroup] = Field(default=None)

    # -------------------------
    # Organizational Data
    # -------------------------

    department_id: str = Field(..., description="Reference to departments._id")
    designation_id: str = Field(..., description="Reference to designations._id")

    manager_id: Optional[str] = Field(
        default=None,
        description="Reference to employees.employee_code or employees._id depending on service design",
    )

    work_location: str = Field(..., min_length=2, max_length=100)
    work_mode: WorkMode = Field(default=WorkMode.OFFICE)

    # -------------------------
    # Employment Details
    # -------------------------

    joining_date: date = Field(...)

    confirmation_date: Optional[date] = Field(default=None)
    probation_end_date: Optional[date] = Field(default=None)
    resignation_date: Optional[date] = Field(default=None)
    last_working_date: Optional[date] = Field(default=None)

    notice_period_days: int = Field(default=30, ge=0, le=365)

    employment_status: EmploymentStatus = Field(default=EmploymentStatus.PROBATION)
    employee_type: EmployeeType = Field(default=EmployeeType.FULL_TIME)

    # -------------------------
    # Leave Management
    # -------------------------

    leave_balances: List[LeaveBalance] = Field(default_factory=list)

    # -------------------------
    # Claim Management
    # -------------------------

    claim_limits: List[ClaimLimit] = Field(default_factory=list)

    # -------------------------
    # Documents and IDs
    # -------------------------

    pan_number: Optional[str] = Field(default=None, max_length=10)
    aadhaar_number: Optional[str] = Field(default=None, max_length=12)
    passport_number: Optional[str] = Field(default=None, max_length=20)
    driving_license: Optional[str] = Field(default=None, max_length=20)

    # -------------------------
    # Address
    # -------------------------

    current_address: Optional[Address] = Field(default=None)
    permanent_address: Optional[Address] = Field(default=None)

    # -------------------------
    # Emergency Contact
    # -------------------------

    emergency_contact: Optional[EmergencyContact] = Field(default=None)

    # -------------------------
    # Bank Details
    # -------------------------

    bank_details: Optional[BankDetails] = Field(default=None)

    # -------------------------
    # Flags and Metadata
    # -------------------------

    is_active: bool = Field(default=True)

    created_by: Optional[str] = Field(default=None)
    updated_by: Optional[str] = Field(default=None)

    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)

    # -------------------------
    # Helper properties
    # -------------------------

    @property
    def full_name(self) -> str:
        """
        Return computed full name.

        Not stored directly in MongoDB.
        Service/response layer can use this for display.
        """
        parts = [self.first_name, self.middle_name, self.last_name]
        return " ".join(part for part in parts if part)

    # -------------------------
    # Validators
    # -------------------------

    @field_validator("company_id")
    @classmethod
    def validate_company_id(cls, value: str) -> str:
        value = value.strip().lower()

        if not value:
            raise ValueError("company_id cannot be empty")

        if not value.replace("_", "").replace("-", "").isalnum():
            raise ValueError("company_id can contain only letters, numbers, hyphen, and underscore")

        return value

    @field_validator("employee_code")
    @classmethod
    def validate_employee_code(cls, value: str) -> str:
        value = value.strip().upper()

        if not value.replace("_", "").replace("-", "").isalnum():
            raise ValueError("employee_code can contain only letters, numbers, hyphen, and underscore")

        return value

    @field_validator("first_name", "last_name")
    @classmethod
    def validate_required_name(cls, value: str) -> str:
        value = value.strip()

        if not value:
            raise ValueError("name cannot be empty")

        if any(char.isdigit() for char in value):
            raise ValueError("name cannot contain numbers")

        return value.title()

    @field_validator("middle_name")
    @classmethod
    def validate_optional_name(cls, value: Optional[str]) -> Optional[str]:
        value = normalize_optional_text(value)

        if value is None:
            return None

        if any(char.isdigit() for char in value):
            raise ValueError("middle_name cannot contain numbers")

        return value.title()

    @field_validator("phone")
    @classmethod
    def validate_phone(cls, value: str) -> str:
        normalized = normalize_phone(value)
        if normalized is None:
            raise ValueError("phone is required")
        return normalized

    @field_validator("alternate_phone")
    @classmethod
    def validate_alternate_phone(cls, value: Optional[str]) -> Optional[str]:
        return normalize_phone(value)

    @field_validator("work_location")
    @classmethod
    def normalize_work_location(cls, value: str) -> str:
        return value.strip().title()

    @field_validator("manager_id", "created_by", "updated_by")
    @classmethod
    def normalize_optional_ids(cls, value: Optional[str]) -> Optional[str]:
        return normalize_optional_text(value)

    @field_validator("pan_number")
    @classmethod
    def validate_pan(cls, value: Optional[str]) -> Optional[str]:
        value = normalize_optional_text(value)

        if value is None:
            return None

        value = value.upper()

        if not PAN_PATTERN.match(value):
            raise ValueError("Invalid PAN number format")

        return value

    @field_validator("aadhaar_number")
    @classmethod
    def validate_aadhaar(cls, value: Optional[str]) -> Optional[str]:
        value = normalize_optional_text(value)

        if value is None:
            return None

        value = value.replace(" ", "")

        if not AADHAAR_PATTERN.match(value):
            raise ValueError("Aadhaar must be exactly 12 digits")

        return value

    @field_validator("passport_number", "driving_license")
    @classmethod
    def normalize_document_ids(cls, value: Optional[str]) -> Optional[str]:
        value = normalize_optional_text(value)

        if value is None:
            return None

        return value.upper()

    @model_validator(mode="after")
    def validate_dates_and_status(self):
        """
        Validate employment date consistency.
        """
        today = date.today()

        if self.date_of_birth is not None:
            if self.date_of_birth >= today:
                raise ValueError("date_of_birth must be in the past")

            minimum_age_years = 14
            age = (
                today.year
                - self.date_of_birth.year
                - ((today.month, today.day) < (self.date_of_birth.month, self.date_of_birth.day))
            )

            if age < minimum_age_years:
                raise ValueError("Employee age must be at least 14 years")

        if self.probation_end_date and self.probation_end_date < self.joining_date:
            raise ValueError("probation_end_date cannot be before joining_date")

        if self.confirmation_date and self.confirmation_date < self.joining_date:
            raise ValueError("confirmation_date cannot be before joining_date")

        if self.resignation_date and self.resignation_date < self.joining_date:
            raise ValueError("resignation_date cannot be before joining_date")

        if self.last_working_date and self.last_working_date < self.joining_date:
            raise ValueError("last_working_date cannot be before joining_date")

        if self.resignation_date and self.last_working_date:
            if self.last_working_date < self.resignation_date:
                raise ValueError("last_working_date cannot be before resignation_date")

        if self.employment_status == EmploymentStatus.ACTIVE:
            if not self.is_active:
                raise ValueError("ACTIVE employee must have is_active=True")

        if self.employment_status in {
            EmploymentStatus.RESIGNED,
            EmploymentStatus.TERMINATED,
            EmploymentStatus.ABSCONDED,
            EmploymentStatus.RETIRED,
        }:
            if self.is_active:
                raise ValueError("Exited employees should have is_active=False")

        if self.employment_status == EmploymentStatus.NOTICE_PERIOD:
            if not self.resignation_date:
                raise ValueError("resignation_date is required for notice_period status")

        return self


