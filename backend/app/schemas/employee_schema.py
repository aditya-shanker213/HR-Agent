class CreateEmployeeRequest(BaseModel):
    """
    Request schema for creating a new employee.

    Employee code is normally generated by service/repository.
    Do not ask frontend to send employee_code unless you want manual override later.
    """

    model_config = ConfigDict(
        str_strip_whitespace=True,
        extra="forbid",
    )

    # Multi-company
    company_id: str = Field(
        default="default",
        min_length=2,
        max_length=100,
        description="Company identifier",
    )

    # Core identity
    user_id: str = Field(
        ...,
        description="Reference to users._id",
    )

    # Personal information
    first_name: str = Field(..., min_length=2, max_length=100)
    middle_name: Optional[str] = Field(default=None, max_length=100)
    last_name: str = Field(..., min_length=2, max_length=100)

    email: EmailStr = Field(..., description="Official company email")
    personal_email: Optional[EmailStr] = None

    phone: str = Field(..., min_length=10, max_length=20)
    alternate_phone: Optional[str] = Field(default=None, max_length=20)

    date_of_birth: Optional[date] = None

    gender: Optional[Gender] = None
    marital_status: Optional[MaritalStatus] = None
    blood_group: Optional[BloodGroup] = None

    # Organizational data
    department_id: str = Field(..., description="Reference to departments._id")
    designation_id: str = Field(..., description="Reference to designations._id")

    manager_id: Optional[str] = Field(
        default=None,
        description="Reference to reporting manager employee id/code depending on service design",
    )

    work_location: str = Field(..., min_length=2, max_length=100)
    work_mode: WorkMode = Field(default=WorkMode.OFFICE)

    # Employment details
    joining_date: date = Field(..., description="Date of joining")
    probation_end_date: Optional[date] = None

    notice_period_days: int = Field(default=30, ge=0, le=365)

    employment_status: EmploymentStatus = Field(default=EmploymentStatus.PROBATION)
    employee_type: EmployeeType = Field(default=EmployeeType.FULL_TIME)

    # Documents
    pan_number: Optional[str] = Field(default=None, max_length=10)
    aadhaar_number: Optional[str] = Field(default=None, max_length=12)
    passport_number: Optional[str] = Field(default=None, max_length=20)
    driving_license: Optional[str] = Field(default=None, max_length=20)

    # Address
    current_address: Optional[Address] = None
    permanent_address: Optional[Address] = None

    # Emergency contact
    emergency_contact: Optional[EmergencyContact] = None

    # Bank details
    bank_details: Optional[BankDetails] = None

    @field_validator("company_id")
    @classmethod
    def validate_company_id(cls, value: str) -> str:
        return normalize_company_id(value)

    @field_validator("middle_name", "manager_id", "passport_number", "driving_license")
    @classmethod
    def clean_optional_text_fields(cls, value: Optional[str]) -> Optional[str]:
        return normalize_optional_text(value)

    @model_validator(mode="after")
    def validate_create_dates(self):
        """
        Basic create-time date validation.

        Deeper validation remains in Employee model/service.
        """
        if self.probation_end_date and self.probation_end_date < self.joining_date:
            raise ValueError("probation_end_date cannot be before joining_date")

        return self


