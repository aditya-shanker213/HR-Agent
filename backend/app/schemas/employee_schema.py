    designation_id: Optional[str] = None
    manager_id: Optional[str] = None

    work_location: Optional[str] = Field(default=None, min_length=2, max_length=100)
    work_mode: Optional[WorkMode] = None

    # Employment details
    confirmation_date: Optional[date] = None
    probation_end_date: Optional[date] = None
    resignation_date: Optional[date] = None
    last_working_date: Optional[date] = None

    notice_period_days: Optional[int] = Field(default=None, ge=0, le=365)

    employment_status: Optional[EmploymentStatus] = None
    employee_type: Optional[EmployeeType] = None

    # Documents
    pan_number: Optional[str] = Field(default=None, max_length=10)
    aadhaar_number: Optional[str] = Field(default=None, max_length=12)
    passport_number: Optional[str] = Field(default=None, max_length=20)
    driving_license: Optional[str] = Field(default=None, max_length=20)

    # Address
    current_address: Optional[Address] = None
    permanent_address: Optional[Address] = None

    # Emergency contact
    emergency_contact: Optional[EmergencyContact] = None

    # Bank details
    bank_details: Optional[BankDetails] = None

    @field_validator("middle_name", "manager_id", "passport_number", "driving_license")
    @classmethod
    def clean_optional_text_fields(cls, value: Optional[str]) -> Optional[str]:
        return normalize_optional_text(value)

    @model_validator(mode="after")
    def validate_at_least_one_field(self):
        """
        Prevent empty update payload.
        """
        values = self.model_dump(exclude_unset=True)

        if not values:
            raise ValueError("At least one field must be provided for update")

        return self

    @model_validator(mode="after")
    def validate_update_dates(self):
        """
        Basic update-time date validation when related fields are present together.
        """
        if self.resignation_date and self.last_working_date:
            if self.last_working_date < self.resignation_date:
                raise ValueError("last_working_date cannot be before resignation_date")

        return self


